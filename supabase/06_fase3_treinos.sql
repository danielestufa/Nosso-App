-- ---------- BIBLIOTECA DE EXERCÍCIOS (compartilhada) ----------
create table if not exists public.exercicios (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  grupo text not null default 'Outros',
  area text not null default 'Outros',
  equipamento text,
  tipo text not null default 'forca' check (tipo in ('forca', 'cardio')),
  imagem text,
  como_fazer text,
  personalizado boolean not null default false,
  criado_por uuid references auth.users(id) on delete set null,
  criado_em timestamptz not null default now()
);

alter table public.exercicios enable row level security;
drop policy if exists "ver exercicios" on public.exercicios;
create policy "ver exercicios" on public.exercicios for select to authenticated using (true);
drop policy if exists "casal cria exercicios" on public.exercicios;
create policy "casal cria exercicios" on public.exercicios for insert to authenticated with check (true);
drop policy if exists "casal edita exercicios" on public.exercicios;
create policy "casal edita exercicios" on public.exercicios for update to authenticated using (true) with check (true);
drop policy if exists "casal apaga exercicios proprios" on public.exercicios;
create policy "casal apaga exercicios proprios" on public.exercicios for delete to authenticated using (personalizado);

-- ---------- FICHA: UM TREINO POR DIA DA SEMANA ----------
create table if not exists public.ficha_dias (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  dia_semana smallint not null check (dia_semana between 0 and 6),
  titulo text not null default 'Treino',
  criado_em timestamptz not null default now(),
  unique (user_id, dia_semana)
);

alter table public.ficha_dias enable row level security;
drop policy if exists "ver fichas" on public.ficha_dias;
create policy "ver fichas" on public.ficha_dias for select to authenticated using (true);
drop policy if exists "gerenciar propria ficha" on public.ficha_dias;
create policy "gerenciar propria ficha" on public.ficha_dias for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.ficha_itens (
  id uuid primary key default gen_random_uuid(),
  ficha_dia_id uuid not null references public.ficha_dias(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  exercicio_id bigint not null references public.exercicios(id) on delete cascade,
  ordem int not null default 0,
  series int not null default 3,
  repeticoes text,
  carga_kg numeric(6,1),
  descanso_s int,
  minutos int,
  km numeric(5,2),
  observacao text,
  criado_em timestamptz not null default now()
);
create index if not exists ficha_itens_dia_idx on public.ficha_itens (ficha_dia_id, ordem);

alter table public.ficha_itens enable row level security;
drop policy if exists "ver itens de ficha" on public.ficha_itens;
create policy "ver itens de ficha" on public.ficha_itens for select to authenticated using (true);
drop policy if exists "gerenciar proprios itens" on public.ficha_itens;
create policy "gerenciar proprios itens" on public.ficha_itens for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ---------- TREINOS FEITOS ----------
create table if not exists public.treinos_realizados (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  data date not null,
  ficha_dia_id uuid references public.ficha_dias(id) on delete set null,
  titulo text,
  iniciado_em timestamptz not null default now(),
  concluido_em timestamptz,
  unique (user_id, data)
);

alter table public.treinos_realizados enable row level security;
drop policy if exists "ver treinos" on public.treinos_realizados;
create policy "ver treinos" on public.treinos_realizados for select to authenticated using (true);
drop policy if exists "gerenciar proprios treinos" on public.treinos_realizados;
create policy "gerenciar proprios treinos" on public.treinos_realizados for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ---------- SÉRIES FEITAS (histórico de carga com data) ----------
create table if not exists public.series_registradas (
  id uuid primary key default gen_random_uuid(),
  treino_id uuid not null references public.treinos_realizados(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  exercicio_id bigint not null references public.exercicios(id) on delete cascade,
  data date not null,
  serie int not null,
  carga_kg numeric(6,1),
  repeticoes int,
  minutos int,
  km numeric(5,2),
  criado_em timestamptz not null default now(),
  unique (treino_id, exercicio_id, serie)
);
create index if not exists series_user_exercicio_idx on public.series_registradas (user_id, exercicio_id, data);

alter table public.series_registradas enable row level security;
drop policy if exists "ver series" on public.series_registradas;
create policy "ver series" on public.series_registradas for select to authenticated using (true);
drop policy if exists "gerenciar proprias series" on public.series_registradas;
create policy "gerenciar proprias series" on public.series_registradas for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

