-- Pasta privada de fotos
insert into storage.buckets (id, name, public)
values ('evolucao', 'evolucao', false)
on conflict (id) do nothing;

drop policy if exists "casal ve fotos de evolucao" on storage.objects;
create policy "casal ve fotos de evolucao" on storage.objects
  for select to authenticated using (bucket_id = 'evolucao');

drop policy if exists "cada um envia suas fotos" on storage.objects;
create policy "cada um envia suas fotos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'evolucao' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "cada um apaga suas fotos" on storage.objects;
create policy "cada um apaga suas fotos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'evolucao' and (storage.foldername(name))[1] = auth.uid()::text);

