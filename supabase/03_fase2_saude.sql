-- ---------- METAS PESSOAIS ----------
create table if not exists public.metas_saude (
  user_id uuid primary key references auth.users(id) on delete cascade,
  agua_ml int not null default 3000,
  copo_ml int not null default 250,
  calorias int not null default 2000,
  proteina_g int not null default 150,
  carboidrato_g int not null default 200,
  gordura_g int not null default 60,
  passos int not null default 8000,
  sono_horas numeric(3,1) not null default 8,
  lembrete_agua_horas int not null default 3,
  atualizado_em timestamptz not null default now()
);

alter table public.metas_saude enable row level security;
drop policy if exists "ver metas" on public.metas_saude;
create policy "ver metas" on public.metas_saude for select to authenticated using (true);
drop policy if exists "criar propria meta" on public.metas_saude;
create policy "criar propria meta" on public.metas_saude for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "editar propria meta" on public.metas_saude;
create policy "editar propria meta" on public.metas_saude for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ---------- ÁGUA ----------
create table if not exists public.registros_agua (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  data date not null,
  ml int not null check (ml > 0 and ml <= 5000),
  criado_em timestamptz not null default now()
