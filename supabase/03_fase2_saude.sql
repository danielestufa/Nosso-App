-- ---------- ALIMENTOS (valores por 100 g, lista compartilhada) ----------
create table if not exists public.alimentos (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  categoria text not null default 'Outros',
  kcal numeric(7,1) not null default 0,
  proteina numeric(6,1) not null default 0,
  carboidrato numeric(6,1) not null default 0,
  gordura numeric(6,1) not null default 0,
  porcao_nome text,
  porcao_g numeric(7,1),
  contem_acucar boolean not null default false,
  personalizado boolean not null default false,
  criado_por uuid references auth.users(id) on delete set null,
  criado_em timestamptz not null default now()
);

alter table public.alimentos enable row level security;
drop policy if exists "ver alimentos" on public.alimentos;
create policy "ver alimentos" on public.alimentos for select to authenticated using (true);
drop policy if exists "casal cadastra alimentos" on public.alimentos;
create policy "casal cadastra alimentos" on public.alimentos for insert to authenticated with check (true);
drop policy if exists "casal edita alimentos" on public.alimentos;
create policy "casal edita alimentos" on public.alimentos for update to authenticated using (true) with check (true);
drop policy if exists "casal apaga alimentos personalizados" on public.alimentos;
create policy "casal apaga alimentos personalizados" on public.alimentos for delete to authenticated using (personalizado);

