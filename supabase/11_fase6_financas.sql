-- ---------- CONTAS (banco, carteira, poupança) ----------
create table if not exists public.fin_contas (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  escopo text not null default 'pessoal' check (escopo in ('pessoal', 'casal')),
  nome text not null,
  tipo text not null default 'corrente' check (tipo in ('corrente', 'poupanca', 'carteira', 'investimento')),
  saldo_inicial numeric(12,2) not null default 0,
  ativa boolean not null default true,
  criado_em timestamptz not null default now()
);

-- ---------- CARTÕES ----------
create table if not exists public.fin_cartoes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  escopo text not null default 'pessoal' check (escopo in ('pessoal', 'casal')),
  nome text not null,
  limite numeric(12,2),
  dia_fechamento int not null check (dia_fechamento between 1 and 31),
  dia_vencimento int not null check (dia_vencimento between 1 and 31),
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

-- ---------- CONTAS A PAGAR (únicas, mensais ou em meses escolhidos) ----------
create table if not exists public.fin_contas_pagar (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  escopo text not null default 'pessoal' check (escopo in ('pessoal', 'casal')),
  grupo uuid,
  descricao text not null,
  valor numeric(12,2) not null check (valor > 0),
  vencimento date not null,
  parcela_num int,
  parcela_total int,
  categoria_id bigint references public.fin_categorias(id) on delete set null,
  pago boolean not null default false,
  pago_em date,
  origem text not null default 'manual',
  origem_id uuid,
  criado_em timestamptz not null default now()
);
create index if not exists fin_contas_pagar_venc_idx on public.fin_contas_pagar (vencimento);

-- ---------- LANÇAMENTOS ----------
create table if not exists public.fin_lancamentos (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  escopo text not null default 'pessoal' check (escopo in ('pessoal', 'casal')),
  tipo text not null check (tipo in ('despesa', 'receita', 'fatura', 'ajuste')),
  descricao text not null,
  valor numeric(12,2) not null,
  valor_terceiros numeric(12,2) not null default 0,
  data date not null,
  categoria_id bigint references public.fin_categorias(id) on delete set null,
  conta_id uuid references public.fin_contas(id) on delete set null,
  cartao_id uuid references public.fin_cartoes(id) on delete set null,
  fatura_mes date,
  grupo_parcela uuid,
  parcela_num int,
  parcela_total int,
  conta_pagar_id uuid references public.fin_contas_pagar(id) on delete set null,
  criado_em timestamptz not null default now()
);
create index if not exists fin_lancamentos_data_idx on public.fin_lancamentos (user_id, data);
create index if not exists fin_lancamentos_fatura_idx on public.fin_lancamentos (cartao_id, fatura_mes);

-- ---------- GASTOS DIVIDIDOS / QUEM DEVE A QUEM ----------
create table if not exists public.fin_divisoes (
  id uuid primary key default gen_random_uuid(),
  lancamento_id uuid references public.fin_lancamentos(id) on delete cascade,
  criado_por uuid not null default auth.uid() references auth.users(id) on delete cascade,
  pagou_por uuid not null references auth.users(id) on delete cascade,
  devedor uuid not null references auth.users(id) on delete cascade,
  descricao text not null,
  data date not null,
  valor_total numeric(12,2) not null,
  valor_devido numeric(12,2) not null check (valor_devido > 0),
  categoria_id bigint references public.fin_categorias(id) on delete set null,
  acertado boolean not null default false,
  acertado_em date,
  criado_em timestamptz not null default now()
);

-- ---------- ORÇAMENTOS POR CATEGORIA ----------
create table if not exists public.fin_orcamentos (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  escopo text not null default 'pessoal' check (escopo in ('pessoal', 'casal')),
  categoria_id bigint not null references public.fin_categorias(id) on delete cascade,
  valor numeric(12,2) not null check (valor > 0),
  criado_em timestamptz not null default now()
);
create unique index if not exists fin_orcamentos_unico on public.fin_orcamentos (escopo, categoria_id, (case when escopo = 'pessoal' then user_id end));

-- ---------- CAIXINHAS E INVESTIMENTOS ----------
create table if not exists public.fin_caixinhas (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  escopo text not null default 'casal' check (escopo in ('pessoal', 'casal')),
  nome text not null,
  tipo text not null default 'caixinha' check (tipo in ('caixinha', 'investimento')),
  meta numeric(12,2),
  prazo date,
  ativa boolean not null default true,
  criado_em timestamptz not null default now()
);

create table if not exists public.fin_caixinha_mov (
  id uuid primary key default gen_random_uuid(),
  caixinha_id uuid not null references public.fin_caixinhas(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  tipo text not null default 'deposito' check (tipo in ('deposito', 'retirada', 'rendimento')),
  valor numeric(12,2) not null check (valor > 0),
  data date not null,
  conta_id uuid references public.fin_contas(id) on delete set null,
  descricao text,
  criado_em timestamptz not null default now()
);

-- ---------- SEGURANÇA ----------
do $$
declare t text;
begin
  foreach t in array array['fin_contas', 'fin_cartoes', 'fin_contas_pagar', 'fin_lancamentos', 'fin_orcamentos', 'fin_caixinhas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "ver pessoal ou casal" on public.%I', t);
    execute format('create policy "ver pessoal ou casal" on public.%I for select to authenticated using (escopo = ''casal'' or user_id = auth.uid())', t);
    execute format('drop policy if exists "criar o proprio" on public.%I', t);
    execute format('create policy "criar o proprio" on public.%I for insert to authenticated with check (user_id = auth.uid())', t);
    execute format('drop policy if exists "editar pessoal ou casal" on public.%I', t);
    execute format('create policy "editar pessoal ou casal" on public.%I for update to authenticated using (escopo = ''casal'' or user_id = auth.uid()) with check (escopo = ''casal'' or user_id = auth.uid())', t);
    execute format('drop policy if exists "apagar pessoal ou casal" on public.%I', t);
    execute format('create policy "apagar pessoal ou casal" on public.%I for delete to authenticated using (escopo = ''casal'' or user_id = auth.uid())', t);
  end loop;
end $$;

alter table public.fin_divisoes enable row level security;
drop policy if exists "casal ve divisoes" on public.fin_divisoes;
create policy "casal ve divisoes" on public.fin_divisoes for select to authenticated using (pagou_por = auth.uid() or devedor = auth.uid());
drop policy if exists "casal cria divisoes" on public.fin_divisoes;
create policy "casal cria divisoes" on public.fin_divisoes for insert to authenticated with check (criado_por = auth.uid() and (pagou_por = auth.uid() or devedor = auth.uid()));
drop policy if exists "casal edita divisoes" on public.fin_divisoes;
create policy "casal edita divisoes" on public.fin_divisoes for update to authenticated using (pagou_por = auth.uid() or devedor = auth.uid()) with check (pagou_por = auth.uid() or devedor = auth.uid());
drop policy if exists "casal apaga divisoes" on public.fin_divisoes;
create policy "casal apaga divisoes" on public.fin_divisoes for delete to authenticated using (criado_por = auth.uid() or pagou_por = auth.uid());

alter table public.fin_caixinha_mov enable row level security;
drop policy if exists "ver movimentos" on public.fin_caixinha_mov;
create policy "ver movimentos" on public.fin_caixinha_mov for select to authenticated
  using (exists (select 1 from public.fin_caixinhas c where c.id = caixinha_id and (c.escopo = 'casal' or c.user_id = auth.uid())));
drop policy if exists "criar movimentos" on public.fin_caixinha_mov;
create policy "criar movimentos" on public.fin_caixinha_mov for insert to authenticated
  with check (user_id = auth.uid() and exists (select 1 from public.fin_caixinhas c where c.id = caixinha_id and (c.escopo = 'casal' or c.user_id = auth.uid())));
drop policy if exists "apagar movimentos" on public.fin_caixinha_mov;
create policy "apagar movimentos" on public.fin_caixinha_mov for delete to authenticated using (user_id = auth.uid());

